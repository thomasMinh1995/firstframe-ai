const assert=require('node:assert/strict');
const {parentWorkflowItems,currentWorkflowItem,workflowItemLabel,cardResult}=require(process.argv[2]+'/draftWorkflowState.js');
const {sceneAfterAdoption}=require(process.argv[2]+'/draftWorkflowActions.js');
const ids=['analysis','intent','plan','plan_review','outline','write','review','draft'];
const make=(id,kind=id,status='pending',scene_id=null)=>({id,kind,status,scene_id,children:[],result:null,started_at:null,finished_at:null,error_code:null});
const base=ids.filter(id=>id!=='write').map(id=>make(id));
const before=JSON.stringify(base);
assert.deepEqual(parentWorkflowItems([]),[]);
assert.deepEqual(parentWorkflowItems(base).map(i=>i.id),ids);
assert.equal(JSON.stringify(base),before);
const first={...make('write:a','write','completed','a'),result:{kind:'write',id:'a',candidate_revision:3},finished_at:'saved'};
const second=make('write:b','write','running','b');
const raw=[...base.slice(0,5),first,second,...base.slice(5)];
const snapshot=JSON.stringify(raw);
const grouped=parentWorkflowItems(raw),write=grouped[5];
assert.deepEqual(grouped.map(i=>i.id),ids,'scene insertion never renumbers parents');
assert.deepEqual(write.children.map(i=>i.id),['write:a','write:b']);
assert.equal(write.status,'running');assert.equal(currentWorkflowItem(grouped).id,'write:b');
const candidate={revision:3,project:{screenplay:{id:'script',scenes:[{id:'a',heading:'Đầu',blocks:[]},{id:'b',heading:'Cuối',blocks:[]}]}}};
assert.equal(workflowItemLabel(second,candidate),'Viết nội dung cảnh 2/2 · Cuối');
assert.equal(cardResult(write,candidate).target,'script');
assert.equal(cardResult(write,{...candidate,revision:2}).target,'','wait for durable source');
const done=parentWorkflowItems(raw.map(i=>i.id==='write:b'?{...i,status:'completed',result:{kind:'write',id:'b',candidate_revision:4}}:i));
assert.equal(done[5].status,'completed');assert.equal(done[5].result.candidate_revision,4);
for(const status of ['warning','failed','interrupted','cancelled','unknown','skipped']){
 const projected=parentWorkflowItems(raw.map(i=>i.id==='write:b'?{...i,status}:i));
 assert.equal(projected[5].status,status,'keep terminal states visible');
}
assert.equal(JSON.stringify(raw),snapshot,'projection never rewrites stored progress');
assert.deepEqual(sceneAfterAdoption(candidate.project.screenplay,'b'),{scriptId:'script',sceneId:'b'});
assert.deepEqual(sceneAfterAdoption(candidate.project.screenplay,'obsolete'),{scriptId:'script',sceneId:'a'});
assert.deepEqual(sceneAfterAdoption(candidate.project.screenplay),{scriptId:'script',sceneId:'a'});
assert.equal(sceneAfterAdoption(null),null);assert.equal(sceneAfterAdoption({id:'empty',scenes:[]}),null);
require.extensions['.css']=()=>{};
const React=require('react'),{renderToStaticMarkup}=require('react-dom/server');
const {DraftWorkflow}=require(process.argv[2]+'/DraftWorkflow.js');
const markup=renderToStaticMarkup(React.createElement(DraftWorkflow,{run:{workflow_items:raw},candidate,following:true,onFollowingChange(){},onRead(){}}));
assert.equal((markup.match(/class="draft-workflow-card is-/g)||[]).length,8);
assert.match(markup,/Đến bước đang chạy/);assert.match(markup,/Đang xử lý: Viết nội dung cảnh 2\/2/);
assert.match(markup,/<details class="draft-workflow-children" open="">/);
assert.match(markup,/data-workflow-id="write:b" tabindex="-1" aria-current="step"/);
assert.match(markup,/Đọc Đầu/);
assert.match(markup,/Cảnh 2 · Cuối/);
assert.match(markup,/1\/2 cảnh đã viết · Tiến trình con/);
assert.match(markup,/class="draft-workflow-child-state"/);
assert.match(markup,/aria-label="Đọc Đầu"[^>]*>Đọc<\/button>/,'compact button keeps its full accessible name');
console.log('PASS stable parents, persisted scene states, active child, stale source, adoption scene fallback and rendered child navigation');
