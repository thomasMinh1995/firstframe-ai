const assert = require('node:assert/strict');
const {randomUUID: uuid} = require('node:crypto');
const {splitScriptBlock, mergeScriptBlock, checkScriptSceneEdit} = require(process.argv[2] + '/screenplayEditing.js');

const first = {id: uuid(), kind: 'action', speaker: '', text: '  Cha đặt thư.\n\nCon ga\u0301i nhìn 🙂.  '};
const dialogue = {id: uuid(), kind: 'dialogue', speaker: 'Con gái', text: 'Không sao đâu cha ạ…\n  '};
const scene = {id: uuid(), source_scene_id: uuid(), heading: 'NỘI. NHÀ – CHIỀU', blocks: [first, dialogue]};
const original = structuredClone(scene), id = uuid(), point = first.text.indexOf('Con');
const split = splitScriptBlock(scene, first.id, point, point, id);
assert.equal(split.blocks[0].id, first.id);
assert.equal(split.blocks[1].id, id);
assert.equal(split.blocks[2], dialogue);
assert.equal(split.blocks[0].text + split.blocks[1].text, first.text);
assert.deepEqual(mergeScriptBlock(split, id), scene, 'split/merge preserves exact Unicode, spacing, IDs and order');
assert.deepEqual(scene, original, 'operations do not mutate the caller buffer');
const selected = splitScriptBlock(scene, first.id, 2, 5, uuid());
assert.equal(selected.blocks[0].text + selected.blocks[1].text, first.text.slice(0, 2) + first.text.slice(5));
const spoken = splitScriptBlock(scene, dialogue.id, 4, 4, uuid());
assert.equal(spoken.blocks[1].speaker, dialogue.speaker);
assert.equal(spoken.blocks[1].id, dialogue.id);
assert.equal(spoken.blocks[2].kind, 'action');
assert.equal(spoken.blocks[2].speaker, '');
assert.equal(spoken.blocks[1].text + spoken.blocks[2].text, dialogue.text);
assert.throws(() => mergeScriptBlock(scene, dialogue.id), /cùng loại/);
assert.throws(() => splitScriptBlock(scene, first.id, 0, 0, dialogue.id), /Không xác định/);
assert.throws(() => splitScriptBlock(scene, first.id, -1, 0, uuid()), /Không xác định/);
const voices = {...scene, blocks: [dialogue, {...dialogue, id: uuid(), speaker: 'Cha'}]};
assert.throws(() => mergeScriptBlock(voices, voices.blocks[1].id), /cùng người nói/);
const sameVoice = {...voices, blocks: [dialogue, {...voices.blocks[1], speaker: dialogue.speaker}]};
assert.equal(mergeScriptBlock(sameVoice, sameVoice.blocks[1].id).blocks[0].text, dialogue.text.repeat(2));
checkScriptSceneEdit({...scene, blocks: [{...first, text: '🙂'.repeat(10000)}]});
assert.throws(() => checkScriptSceneEdit({...scene, blocks: [{...first, text: 'x'.repeat(10001)}]}), /giới hạn/);
assert.throws(() => checkScriptSceneEdit({...scene, blocks: [{...dialogue, speaker: 'x'.repeat(201)}]}), /giới hạn/);
assert.throws(() => checkScriptSceneEdit(scene, 1), /số khối/);
checkScriptSceneEdit({...scene, blocks: [{...dialogue, text: ''}]});
assert.deepEqual(scene, original);
console.log('PASS continuous editor contract: exact split/merge, stable IDs, no mutation, dialogue mapping, incompatible merge rejection, draft and Unicode limits');
